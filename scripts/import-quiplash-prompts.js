/**
 * scripts/import-quiplash-prompts.js — rebuilds server/prompts-quiplash.json.
 *
 *   node scripts/import-quiplash-prompts.js
 *
 * Downloads the Quiplash XL, Quiplash 2 and Quiplash 3 (rounds 1 and 2)
 * prompt files from a public GitHub mirror of the game files, converts them
 * to our format, and drops anything the game can't use:
 *   - flagged explicit by the source ("x": true)
 *   - needs a player's name filled in (<ANY PLAYER>, includesPlayerName)
 *   - more than one blank, leftover markup, empty, or over 120 characters
 *   - machine-translated (Spanish) entries in the XL file
 *   - duplicates of server/prompts.json or of each other
 *
 * Final-round prompts aren't imported: Quiplash's final rounds need three
 * answers or special formats (Thriplash, Acro/Comic/Word Lash).
 *
 * This content belongs to Jackbox Games. It lives in its own file so it can
 * be removed by deleting server/prompts-quiplash.json.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'server', 'prompts-quiplash.json');
const REPO = 'https://github.com/jackboxpt/JackboxPartyPack-Localization';
const RAW = 'https://raw.githubusercontent.com/jackboxpt/JackboxPartyPack-Localization/main/en-us%20(default)';
const SOURCES = [
  { prefix: 'qxl', game: 'Quiplash XL', file: 'The Jackbox Party Pack 2/games/Quiplash/content/QuiplashQuestion.jet' },
  { prefix: 'qp2', game: 'Quiplash 2', file: 'The Jackbox Party Pack 3/games/Quiplash2/content/QuiplashQuestion.jet' },
  { prefix: 'qp3r1', game: 'Quiplash 3', file: 'The Jackbox Party Pack 7/games/Quiplash3/content/Quiplash3Round1Question.jet' },
  { prefix: 'qp3r2', game: 'Quiplash 3', file: 'The Jackbox Party Pack 7/games/Quiplash3/content/Quiplash3Round2Question.jet' },
];
const MAX_LENGTH = 120;
const BLANK = '_____';
const SPANISH = /\b(una?|el|la|los|las|que|del?|con|para|tu|es|por|si|cosa|mas|peor|mejor|nombre|nunca|nada|puedes|muy|seria)\b/gi;

/** Lowercase letters and digits only, so "Foo: _____" and "foo" match. */
function normalize(text) {
  return text.replaceAll(BLANK, ' ').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

/** Converts a source prompt to our format, or returns the reason it was dropped. */
function convert(entry) {
  if (entry.x) return { drop: 'explicit' };
  if (entry.includesPlayerName || /<ANY ?PLAYER>/i.test(entry.prompt)) return { drop: 'needs a player name' };
  let text = String(entry.prompt ?? '')
    .replace(/<\/?i>/gi, '')
    .replace(/_{2,}/g, '<BLANK>')
    .replace(/\s+/g, ' ')
    .trim();
  if (!text) return { drop: 'empty' };
  if ((text.match(SPANISH) ?? []).length >= 2) return { drop: 'not English' };
  const blanks = text.split('<BLANK>').length - 1;
  if (blanks > 1) return { drop: 'more than one blank' };
  text = text.replace('<BLANK>', BLANK);
  if (/[<>[\]{}]/.test(text)) return { drop: 'leftover markup' };
  if (blanks === 0) {
    text = /[?!.…]$/.test(text) ? `${text} ${BLANK}` : `${text}: ${BLANK}`;
  }
  if (text.length > MAX_LENGTH) return { drop: `over ${MAX_LENGTH} characters` };
  return { text };
}

const existing = JSON.parse(readFileSync(path.join(ROOT, 'server', 'prompts.json'), 'utf8'));
const seen = new Set(existing.map((p) => normalize(p.text)));
const prompts = [];
const dropped = {};
let mined = 0;

for (const source of SOURCES) {
  const url = `${RAW}/${source.file.split('/').map(encodeURIComponent).join('/')}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed (${res.status}): ${url}`);
  const { content } = await res.json();
  mined += content.length;
  for (const entry of content) {
    const { text, drop } = convert(entry);
    const reason = drop ?? (seen.has(normalize(text)) ? 'duplicate' : null);
    if (reason) {
      dropped[reason] = (dropped[reason] ?? 0) + 1;
      continue;
    }
    seen.add(normalize(text));
    prompts.push({ id: `${source.prefix}-${entry.id}`, text, final: false });
  }
}

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      source: `Quiplash XL, Quiplash 2 and Quiplash 3 prompts, mirrored at ${REPO}`,
      license: 'None stated by the mirror. The prompts are © Jackbox Games, Inc.',
      note: 'Generated by scripts/import-quiplash-prompts.js. Delete this file to remove these prompts.',
      prompts,
    },
    null,
    2,
  )}\n`,
);

console.log(`Mined ${mined} prompts, kept ${prompts.length}.`);
for (const [reason, count] of Object.entries(dropped).sort((a, b) => b[1] - a[1])) {
  console.log(`  dropped ${count}: ${reason}`);
}
